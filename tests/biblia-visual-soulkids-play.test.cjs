"use strict";
const fs=require("node:fs");
const path=require("node:path");
const assert=require("node:assert/strict");
const root=path.resolve(__dirname,"..");
const read=p=>fs.readFileSync(path.join(root,p),"utf8");
const data=JSON.parse(read("dados/personagens-soulkids-play.json"));
const doc=read("docs/BIBLIA_VISUAL_SOULKIDS_PLAY.md");
const original=read("docs/BIBLIA_PERSONAGENS_SOULKIDS.md");
const names=["ritinha","tonico","luca","lia","maya","ravi","ray"];
assert.deepEqual(data.characters.map(x=>x.id).sort(),[...names].sort());
assert.equal(new Set(data.characters.map(x=>x.id)).size,7);
assert.deepEqual(data.rules.playable_characters,["ritinha","tonico","luca","lia","maya"]);
assert.deepEqual(data.rules.hosts,["ravi","ray"]);
assert.equal(data.rules.max_local_players,4);
assert.equal(data.rules.same_character_for_multiple_players,false);
assert.equal(data.rules.game_categories.length,6);
assert.equal(data.rules.audio_autoplay,false);
assert.equal(data.rules.no_unapproved_dubbed_voices,true);
assert.equal(data.rules.andador_maya_must_remain,true);
assert.equal(data.source.archived_in_repository,false);
const get=id=>data.characters.find(x=>x.id===id);
assert.ok(get("maya").visual.some(x=>x.includes("andador azul")));
assert.ok(get("maya").animation_notes.some(x=>x.includes("andador")));
assert.equal(get("maya").sprite_status,"pendente_andador_obrigatorio");
assert.ok(get("ritinha").visual.some(x=>x.includes("oculos")));
assert.ok(get("ritinha").visual.some(x=>x.includes("short laranja")));
assert.ok(get("ritinha").conflicts.some(x=>x.includes("amarelo")));
assert.equal(get("ravi").signature.text,"Boa, jovem!");
assert.equal(get("ravi").signature.type,"official_catchphrase");
assert.equal(get("ritinha").signature.type,"official_catchphrase");
assert.equal(get("tonico").signature.type,"rhythmic_mark");
assert.equal(get("luca").signature.type,"speech_pattern");
assert.equal(get("lia").signature.type,"contextual_reaction");
assert.equal(get("maya").signature.text,null);
assert.equal(get("ray").signature.text,null);
assert.equal(data.characters.filter(x=>x.voice_approved).length,1);
assert.equal(data.characters.every(x=>x.animation_notes.length>=3),true);
assert.equal(data.characters.filter(x=>x.existing_sprite).length,1);
assert.ok(fs.existsSync(path.join(root,"ritinha-passos.webp")));
for(const c of data.characters){
  assert.ok(c.visual.length>=4,"Visual incompleto: "+c.id);
  assert.ok(doc.includes("### "+c.name.toUpperCase()+" —"),"Sem ficha: "+c.id);
}
assert.ok(original.includes("BIBLIA_VISUAL_SOULKIDS_PLAY.md"));
assert.ok(doc.includes("não ao repositório")||doc.includes("ainda não ao repositório"));
console.log("PASSOU — Bíblia Visual SoulKids Play: 7 fichas, 5 jogáveis, 2 mediadores, 6 categorias, áudio e andador conferidos.");